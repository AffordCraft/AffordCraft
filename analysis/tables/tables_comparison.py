def rsum(sm, *keys):
    v = [sm.get(k) for k in keys if sm.get(k) is not None]
    return sum(v) if v else None


def rcol(mid):
    m = EXT.get(mid)
    sub = (m or {}).get(CHOSEN.get(mid, "subset200"))  # same track as the method's Table 1 row
    if not sub or ((sub["counts"]["pending"] > 0 or sub["counts"]["infra_blocked"] > 0) and not SIM):
        return {}
    sm = sub["stage_medians"]
    t = sub["timing"]
    c = sub["counts"]
    nat = t["native_applies"]
    ct = clean_ext(mid)
    if ct:
        t = clean_fact_timing(ct[0], t, c, sub["denominator"])
        sm = ct[1]  # clean timing run, pass rates of the registered run
    perc = {
        "physx-anything-v0.1": sm.get("vlm_seconds"),
        "physx-omni-v0.1": sm.get("representation_seconds"),
        "pact-v0.1": sm.get("adapter_total"),
        "partcrafter-v0.1": sm.get("vlm_seconds"),
        "trellis2-4b-v0.1": sm.get("preprocess_seconds"),
        "articulate-anything-v0.1": sm.get("retrieval_seconds"),
        "gpt6-astra-agent-v0.1": None,
    }[mid]
    gen = {
        "physx-anything-v0.1": rsum(sm, "decoder_seconds", "split_seconds", "export_seconds"),
        "physx-omni-v0.1": sm.get("geometry_total_runtime_seconds"),
        "pact-v0.1": sm.get("official_wall_seconds"),
        "partcrafter-v0.1": rsum(sm, "generation_seconds", "export_seconds"),
        "trellis2-4b-v0.1": rsum(sm, "generation_seconds", "export_seconds"),
        "articulate-anything-v0.1": rsum(sm, "link_seconds", "joint_seconds"),
        "gpt6-astra-agent-v0.1": sm.get("wall_seconds"),
    }[mid]
    e2e = t["e2e_native_median_s"] if nat else t["e2e_adapted_median_s"]
    e2m = t["e2e_native_mean_s"] if nat else t["e2e_adapted_mean_s"]
