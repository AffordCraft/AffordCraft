def clean_peak(mid):
    s = CLEAN["external"][mid]
    lw = s.get("lane_walls") or {}
    v = (
        [(d.get("monitor") or {}).get("peak_gib") for k in ("representation", "geometry") for d in lw.get(k, [])]
        if mid == "physx-omni-v0.1"
        else [lw.get("monitor_peak_gib")]
    )
    v = [x for x in v if x]
    return max(v) if v else None


def clean_ext(mid):
    """(timing, stage medians) of one external method from the clean run, or None."""
    if not CLEAN_OURS or mid not in CLEAN["external"]:
        return None
    s = CLEAN["external"][mid]
    t = dict(s["timing"])
    t["peak_gib_max"] = max([x for x in (clean_peak(mid), t.get("peak_gib_max")) if x] or [None])
    t["clean_worker"] = s.get("clean_worker") or {}
    t["gated"] = s.get("gated")
    return t, s["stage_medians"]


def clean_fact_timing(tt, t, c, n):
    """the registered run's timing dict with every timing value replaced by the clean run's (same keys as the aggregate)."""
    w = tt["clean_worker"]
    r = dict(t)
    for kk in (
        "stage1_median_s",
        "geometry_median_s",
        "native_gate_median_s",
        "adapted_materialize_median_s",
        "e2e_native_median_s",
        "e2e_native_p95_s",
        "e2e_adapted_median_s",
        "e2e_adapted_p95_s",
    ):
        r[kk] = tt.get(kk)
    r.update(
        e2e_native_mean_s=w.get("native_mean_s"),
        e2e_adapted_mean_s=w.get("adapted_mean_s"),
        worker_minutes_per_native_pass=(
            round(tt["e2e_native_median_s"] / 60 / (c["native_pass"] / n), 1)
            if tt.get("e2e_native_median_s") and c["native_pass"]
            else None
        ),
        worker_minutes_per_adapted_pass=(
            round(tt["e2e_adapted_median_s"] / 60 / (c["adapted_pass"] / n), 1)
            if tt.get("e2e_adapted_median_s") and c["adapted_pass"]
            else None
        ),
        worker_minutes_per_native_pass_mean=(
            round(w["native_mean_s"] / 60 / (c["native_pass"] / n), 1)
            if w.get("native_mean_s") and c["native_pass"]
            else None
        ),
        worker_minutes_per_adapted_pass_mean=(
            round(w["adapted_mean_s"] / 60 / (c["adapted_pass"] / n), 1)
            if w.get("adapted_mean_s") and c["adapted_pass"]
            else None
        ),
        cost_basis="median time per input / pass rate of the row",
        peak_gib_max=tt.get("peak_gib_max"),
        source=CLEAN_SRC,
        gated=tt.get("gated"),
        scope="clean timing run (32-input sample); pass rates of the registered run",
    )
    return r


