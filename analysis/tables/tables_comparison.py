def q_nearest(v, q):
    v = sorted(v)
    return v[max(math.ceil(q * len(v)), 1) - 1] if v else None


def within_budget(rows, tk, pk, b=BUDGET_S):
    return (
        100.0 * sum(1 for r in rows if r.get(pk) and r.get(tk) is not None and r[tk] <= b) / len(rows) if rows else None
    )


def api_tag(mid, tag):
    if mid not in API_TIMED:
        return tag
    return r"$^{\ddagger\S}$" if tag == DDG else r"$^\S$"


